<h1>Términos y Condiciones de Uso</h1>
<p class="fecha">Última actualización: 23 de noviembre de 2026</p>

<p>Estos Términos y Condiciones regulan el uso de la aplicación móvil <strong>Astro Restaurante</strong> (la "App"), propiedad de <strong>ASTRO POLLO</strong> (el "Restaurante"), disponible para Android e iOS. Al descargar, registrarte o usar la App aceptas estos términos. Si no estás de acuerdo, no utilices la App.</p>

<h2>1. Objeto de la App</h2>
<p>La App permite consultar el menú del Restaurante, realizar pedidos de comida a domicilio dentro de las zonas de cobertura, dar seguimiento al estado de los pedidos y recibir notificaciones y promociones.</p>

<h2>2. Registro y cuenta</h2>
<ul>
  <li>Para realizar pedidos debes crear una cuenta con información verdadera y actualizada.</li>
  <li>Eres responsable de mantener la confidencialidad de tu usuario y contraseña, y de toda actividad realizada desde tu cuenta.</li>
  <li>El Restaurante puede suspender o cancelar cuentas que proporcionen datos falsos, realicen pedidos fraudulentos o hagan un uso indebido de la App.</li>
</ul>

<h2>3. Pedidos</h2>
<ul>
  <li>Los pedidos están sujetos a disponibilidad de productos, al horario de servicio y a que la dirección de entrega se encuentre dentro de una zona de cobertura.</li>
  <li>Algunas zonas pueden tener un monto mínimo de compra y un tiempo de entrega mayor.</li>
  <li>Un pedido se considera confirmado cuando el Restaurante lo acepta; recibirás la confirmación en la App.</li>
  <li>El Restaurante puede rechazar o cancelar un pedido por falta de producto, problemas con la dirección, fuerza mayor o sospecha de uso indebido. En ese caso se te notificará en la App.</li>
  <li>Puedes cancelar tu pedido desde la App mientras el Restaurante aún no lo haya comenzado a preparar.</li>
</ul>

<h2>4. Precios y pago</h2>
<ul>
  <li>Los precios mostrados en la App están expresados en dólares de los Estados Unidos (USD) e incluyen los impuestos aplicables, salvo que se indique lo contrario.</li>
  <li>Los precios, el menú y las promociones pueden cambiar sin previo aviso; se respetará el precio vigente al momento de confirmar el pedido.</li>
  <li>El pago se realiza al momento de la entrega, según los métodos de pago aceptados por el Restaurante.</li>
</ul>

<h2>5. Entregas</h2>
<ul>
  <li>Los tiempos de entrega mostrados son aproximados y pueden variar por tráfico, clima, demanda u otras circunstancias.</li>
  <li>Debes proporcionar una dirección exacta y estar disponible para recibir el pedido. Si el repartidor no puede realizar la entrega por causas atribuibles al cliente, el pedido podrá darse por entregado.</li>
</ul>

<h2>6. Cupones y promociones</h2>
<p>Los cupones y promociones tienen las condiciones, vigencia y límites de uso indicados en cada uno, no son canjeables por dinero y pueden ser modificados o retirados por el Restaurante en cualquier momento.</p>

<h2>7. Reclamos</h2>
<p>Si tu pedido llegó incompleto, equivocado o en mal estado, comunícate con el Restaurante lo antes posible a través de los medios de contacto indicados abajo. Cada caso será revisado conforme a la Ley de Protección al Consumidor de El Salvador.</p>

<h2>8. Uso adecuado</h2>
<p>Te comprometes a no utilizar la App con fines ilícitos, no realizar pedidos falsos, no intentar acceder a sistemas o datos sin autorización y no interferir con el funcionamiento de la App.</p>

<h2>9. Datos personales</h2>
<p>Para prestar el servicio recopilamos tu nombre, teléfono, correo electrónico, direcciones de entrega y el historial de pedidos. Estos datos se usan únicamente para gestionar tus pedidos, comunicarnos contigo y enviarte notificaciones de la App, y no se venden a terceros. Puedes solicitar la eliminación de tu cuenta y datos en <a href="{{ url('/formulario/eliminacioncuenta') }}">este formulario</a>.</p>

